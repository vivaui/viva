var (
	textareaUI       = tree.Feature("textarea")
	textareaField    = tree.ID(textareaUI, "field")
	textareaReadOnly = tree.ID(textareaUI, "read-only")
	textareaDisabled = tree.ID(textareaUI, "disabled")
	textareaInvalid  = tree.ID(textareaUI, "invalid")
)

const (
	textareaDefaultValue   = "Viva 使用原生 GPU 渲染。空闲时不会持续提交帧：没有输入、动画或网络事件时，窗口不会被重绘，也不会有后台定时器在轮询。\n第二段很短。"
	textareaDefaultEnglish = "Viva renders with the native GPU. An idle window keeps submitting no frames: with no input, animation, or network events it is not repainted, and no background timer polls.\nThe second paragraph is short."
	textareaGrowValue      = "输入更多文字，框会随内容长高，到五行时开始滚动。"
	textareaGrowEnglish    = "Type more text and the box grows with it, then scrolls after five rows."
	textareaGrowMaxRows    = 5
)

// textareaInitialValue is the text the example starts with in the preview's
// language, including the value the platform editor is seeded with.
func (state *State) textareaInitialValue() string {
	if state.exampleID == "grow" {
		return state.Text(textareaGrowValue, textareaGrowEnglish)
	}
	return state.Text(textareaDefaultValue, textareaDefaultEnglish)
}

func (state *State) paintTextarea(canvas *gfx.Canvas, theme gfx.Theme, size gfx.Size) {
	var slots [3]ui.Box
	var snapshots [3]components.TextareaSnapshot
	count := 0
	state.drawPage(canvas, theme, size, 540, state.Text("Textarea · 多行编辑", "Textarea · Multi-line editing"), func(c ui.C) {
		if state.exampleID == "states" {
			tooShort := state.Text("内容过短", "Too short")
			generated := state.Text("由系统生成\n不可编辑", "Generated by the system\nNot editable")
			ui.Row(c).Gap(12).Children(func() {
				snapshots[0] = components.TextareaSnapshot{
					ID: textareaInvalid, Label: state.Text("错误说明", "Invalid field"), Value: tooShort, DisplayValue: tooShort, Invalid: true, ReadOnly: true,
				}
				slots[0] = ui.Slot(c).Grow(1).Basis(0).Height(104)
				snapshots[1] = components.TextareaSnapshot{
					ID: textareaReadOnly, Label: state.Text("只读说明", "Read-only field"), Value: generated, DisplayValue: generated, ReadOnly: true,
				}
				slots[1] = ui.Slot(c).Grow(1).Basis(0).Height(104)
			})
			snapshots[2] = components.TextareaSnapshot{
				ID: textareaDisabled, Label: state.Text("禁用说明", "Disabled field"), Placeholder: state.Text("当前不可填写", "Currently unavailable"), Disabled: true,
			}
			slots[2] = ui.Slot(c).Height(72)
			count = 3
			return
		}
		initial := state.textareaInitialValue()
		value := state.fieldValue(initial)
		focused := state.editing && canvas.Focused() == textareaField
		snapshot := components.TextareaSnapshot{
			ID: textareaField, Label: state.Text("项目说明", "Project description"), Hint: state.Text("支持多行文本", "Supports multiple lines"),
			Value: value, DisplayValue: value,
			ReadOnly: !state.editing, Focused: focused, HideEditorText: true, ShowCaret: focused,
			Layout: state.textarea,
		}
		if state.editing {
			selection := state.editor.Selection()
			snapshot.SelectionStart, snapshot.SelectionEnd = byteOffsetOfRune(value, selection.Start), byteOffsetOfRune(value, selection.End)
			snapshot.Caret = byteOffsetOfRune(value, state.editor.Caret())
			snapshot.ShowCaret = focused && selection.Start == selection.End
			if marked, composing := state.editor.Composition(); composing {
				snapshot.CompositionStart, snapshot.CompositionEnd = byteOffsetOfRune(value, marked.Start), byteOffsetOfRune(value, marked.End)
			}
		}
		if state.exampleID == "selection" {
			selected := state.Text("选择这段文字\n输入法组合文本", "Select this text\nComposition text")
			caret := 0
			for caret < len(selected) && selected[caret] != '\n' {
				caret++
			}
			snapshot.Value = selected
			snapshot.DisplayValue = selected
			snapshot.Layout = nil
			snapshot.ReadOnly = true
			snapshot.Focused = true
			snapshot.ShowCaret = true
			snapshot.Caret = caret
			snapshot.SelectionStart = 0
			snapshot.SelectionEnd = 6
			snapshot.CompositionStart = caret + 1
			snapshot.CompositionEnd = len(selected)
		}
		height := float32(142)
		if state.exampleID == "grow" {
			width := min(size.Width-48, 540)
			height = min(state.textarea.ContentHeight(canvas, theme, value, width, false), float32(textareaGrowMaxRows)*20+16)
		}
		snapshots[0] = snapshot
		slots[0] = ui.Slot(c).Height(height)
		count = 1
		text := state.Text("编辑与 IME 事件由应用持有；换行、行内定位与滚动由 Viva 的 TextareaLayout 负责。", "Editing and IME events stay with the app; TextareaLayout handles wrapping, caret placement, and scrolling.")
		if state.exampleID == "selection" {
			text = state.Text("蓝色选择区、插入点与组合文本均来自调用方快照。", "The selection, caret, and composition text come from the caller's snapshot.")
		}
		caption(c, text)
	})
	for index := 0; index < count; index++ {
		components.PaintTextarea(canvas, theme, slots[index].Rect(), snapshots[index])
	}
}

// textareaKey moves the caret by visual row for the arrows, Home, End and the
// page keys: the text system knows one line, the layout knows the rows.
func (state *State) textareaKey(event gfx.KeyEvent) gfx.EventResult {
	if !state.editing || event.Target != textareaField || state.textarea == nil {
		return gfx.EventResult{}
	}
	movement, extend := components.TextareaMovementForKey(event.Key, event.Modifiers)
	if movement == components.TextareaMoveNone {
		return gfx.EventResult{}
	}
	value := state.editor.String()
	to := state.textarea.Move(value, byteOffsetOfRune(value, state.editor.Caret()), movement)
	state.editor.MoveTo(utf8.RuneCountInString(value[:to]), extend)
	return gfx.EventResult{Handled: true, Repaint: true}
}

func (state *State) textareaScroll(event gfx.ScrollEvent) gfx.EventResult {
	if state.textarea == nil {
		return gfx.EventResult{}
	}
	state.textarea.ScrollBy(event.DeltaY)
	return gfx.EventResult{Handled: true, Repaint: true}
}

// byteOffsetOfRune is the byte offset of the n-th rune of value.
func byteOffsetOfRune(value string, n int) int {
	for offset := range value {
		if n == 0 {
			return offset
		}
		n--
	}
	return len(value)
}
