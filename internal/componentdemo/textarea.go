var (
	textareaUI       = tree.Feature("textarea")
	textareaField    = tree.ID(textareaUI, "field")
	textareaReadOnly = tree.ID(textareaUI, "read-only")
	textareaDisabled = tree.ID(textareaUI, "disabled")
	textareaInvalid  = tree.ID(textareaUI, "invalid")
)

const (
	textareaDefaultValue   = "Viva 使用原生 GPU 渲染。空闲时不会持续提交帧：没有输入、动画或网络事件时，窗口不会被重绘，也不会有后台定时器在轮询。\n第二段很短。"
	textareaDefaultEnglish = "Viva renders with the native GPU. An idle window keeps submitting no frames: with no input, animation, or network events it is not repainted, and no background timer polls.\nThe second paragraph is short."
	textareaGrowValue      = "输入更多文字，框会随内容长高，到五行时开始滚动。"
	textareaGrowEnglish    = "Type more text and the box grows with it, then scrolls after five rows."
	textareaGrowMaxRows    = 5
)

// textareaInitialValue is the text the example starts with in the preview's
// language, including the value the platform editor is seeded with.
func (state *State) textareaInitialValue() string {
	if state.exampleID == "grow" {
		return state.Text(textareaGrowValue, textareaGrowEnglish)
	}
	return state.Text(textareaDefaultValue, textareaDefaultEnglish)
}

func (state *State) paintTextarea(canvas *gfx.Canvas, theme gfx.Theme, size gfx.Size) {
	switch state.exampleID {
	case "default":
		state.paintTextareaPage(canvas, theme, size)
	case "grow":
		state.paintTextareaGrowPage(canvas, theme, size)
	case "states":
		state.paintTextareaStatesPage(canvas, theme, size)
	default:
		state.paintTextareaSelection(canvas, theme, size)
	}
}

// paintTextareaGrowPage is the page TextArea sized from its own rows: AutoGrow
// measures the text the box paints, caps the height at five rows and leaves the
// rows scrolling inside it past that.
func (state *State) paintTextareaGrowPage(canvas *gfx.Canvas, theme gfx.Theme, size gfx.Size) {
	initial := state.textareaInitialValue()
	label := state.Text("项目说明", "Project description")
	state.drawPage(canvas, theme, size, 540, state.Text("Textarea · 多行编辑", "Textarea · Multi-line editing"), func(c ui.C) {
		field := ui.State[ui.Field](c, "notes")
		state.bindPageField(field, initial)
		ui.TextAreaID(c, textareaField, field, label, "").ReadOnly(!state.editing).AutoGrow(textareaGrowMaxRows)
		caption(c, state.Text("高度由控件内容决定，最多五行；超过五行后在框内滚动。", "The control is as tall as its text, up to five rows; after that the box scrolls."))
	})
}

// paintTextareaStatesPage shows the invalid, read-only and disabled states as
// page TextAreas: the field state carries the look, the missing editor and the
// disabled semantics.
func (state *State) paintTextareaStatesPage(canvas *gfx.Canvas, theme gfx.Theme, size gfx.Size) {
	state.drawPage(canvas, theme, size, 540, state.Text("Textarea · 多行编辑", "Textarea · Multi-line editing"), func(c ui.C) {
		tooShort := state.pageFieldText(c, "invalid", state.Text("内容过短", "Too short"))
		tooShort.Invalid = true
		generated := state.pageFieldText(c, "read-only", state.Text("由系统生成\n不可编辑", "Generated by the system\nNot editable"))
		generated.ReadOnly = true
		unavailable := state.pageFieldText(c, "disabled", "")
		unavailable.Disabled = true
		ui.Row(c).Gap(12).Children(func() {
			ui.TextAreaID(c, textareaInvalid, tooShort, state.Text("错误说明", "Invalid field"), "").
				Grow(1).Basis(0).Height(104).ReadOnly(true)
			ui.TextAreaID(c, textareaReadOnly, generated, state.Text("只读说明", "Read-only field"), "").
				Grow(1).Basis(0).Height(104).ReadOnly(true)
		})
		ui.TextAreaID(c, textareaDisabled, unavailable, state.Text("禁用说明", "Disabled field"), state.Text("当前不可填写", "Currently unavailable")).Height(72)
	})
}

// paintTextareaSelection stays on the canvas API: the example shows a
// composition and a separate selection at once, and an editor's selection
// always lies inside its composition, so the page Field cannot hold both.
func (state *State) paintTextareaSelection(canvas *gfx.Canvas, theme gfx.Theme, size gfx.Size) {
	var slot ui.Box
	selected := state.Text("选择这段文字\n输入法组合文本", "Select this text\nComposition text")
	caret := 0
	for caret < len(selected) && selected[caret] != '\n' {
		caret++
	}
	snapshot := components.TextareaSnapshot{
		ID: textareaField, Value: selected, DisplayValue: selected,
		ReadOnly: true, Focused: true, ShowCaret: true, Caret: caret,
		SelectionStart: 0, SelectionEnd: 6,
		CompositionStart: caret + 1, CompositionEnd: len(selected),
	}
	state.drawPage(canvas, theme, size, 540, state.Text("Textarea · 多行编辑", "Textarea · Multi-line editing"), func(c ui.C) {
		slot = ui.Slot(c).Height(142)
		caption(c, state.Text("蓝色选择区、插入点与组合文本均来自调用方快照。", "The selection, caret, and composition text come from the caller's snapshot."))
	})
	components.PaintTextarea(canvas, theme, slot.Rect(), snapshot)
}

// paintTextareaPage is the page TextArea of the editable example: the value is
// the Field's, so the platform text service and the preview share one editor.
func (state *State) paintTextareaPage(canvas *gfx.Canvas, theme gfx.Theme, size gfx.Size) {
	initial := state.textareaInitialValue()
	label := state.Text("项目说明", "Project description")
	hint := state.Text("支持多行文本", "Supports multiple lines")
	state.drawPage(canvas, theme, size, 540, state.Text("Textarea · 多行编辑", "Textarea · Multi-line editing"), func(c ui.C) {
		field := ui.State[ui.Field](c, "notes")
		state.bindPageField(field, initial)
		field.Hint = hint
		ui.TextAreaID(c, textareaField, field, label, "").Height(142)
		caption(c, state.Text("编辑与 IME 事件由应用持有；换行、行内定位与滚动由 Viva 的 TextareaLayout 负责。", "Editing and IME events stay with the app; TextareaLayout handles wrapping, caret placement, and scrolling."))
	})
}

// textareaKey moves the caret by visual row for the arrows, Home, End and the
// page keys: the text system knows one line, the layout knows the rows.
func (state *State) textareaKey(event gfx.KeyEvent) gfx.EventResult {
	if !state.editing || event.Target != textareaField || state.textarea == nil {
		return gfx.EventResult{}
	}
	movement, extend := components.TextareaMovementForKey(event.Key, event.Modifiers)
	if movement == components.TextareaMoveNone {
		return gfx.EventResult{}
	}
	value := state.editor.String()
	to := state.textarea.Move(value, byteOffsetOfRune(value, state.editor.Caret()), movement)
	state.editor.MoveTo(utf8.RuneCountInString(value[:to]), extend)
	return gfx.EventResult{Handled: true, Repaint: true}
}

func (state *State) textareaScroll(event gfx.ScrollEvent) gfx.EventResult {
	if state.textarea == nil {
		return gfx.EventResult{}
	}
	state.textarea.ScrollBy(event.DeltaY)
	return gfx.EventResult{Handled: true, Repaint: true}
}

// byteOffsetOfRune is the byte offset of the n-th rune of value.
func byteOffsetOfRune(value string, n int) int {
	for offset := range value {
		if n == 0 {
			return offset
		}
		n--
	}
	return len(value)
}
