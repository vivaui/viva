// viva form writes, for each struct of a package whose fields are tagged form, a
// method Form(c ui.C) ui.Box declaring a control for each tagged field. It reads
// the package's source as syntax only: what control a field gets follows from how its
// type is written, so it needs no build and works on a package that does not compile
// yet. The generated code is ordinary page code, with no reflection at run time.

// formFile is the file viva form writes in the package's directory.
const formFile = "viva_form.go"

const formHeader = "// Code generated by viva form; DO NOT EDIT."

func runForm(arguments []string, output, errorOutput io.Writer) error {
	flags := flag.NewFlagSet("form", flag.ContinueOnError)
	directory, names := ".", ""
	flags.StringVar(&directory, "C", directory, "package directory")
	flags.StringVar(&names, "type", names, "comma-separated struct types (default: every struct with a form tag)")
	c, _ := findCommand("form")
	rest, helped, err := parseFlags(c, flags, arguments, output)
	if helped || err != nil {
		return err
	}
	if len(rest) != 0 {
		return errors.New("form takes no packages: run it in the package's directory, or pass -C")
	}
	var wanted []string
	for _, name := range strings.Split(names, ",") {
		if name = strings.TrimSpace(name); name != "" {
			wanted = append(wanted, name)
		}
	}
	source, made, err := generateForms(directory, wanted)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(directory, formFile), source, 0o644); err != nil {
		return err
	}
	fmt.Fprintf(output, "wrote %s: Form for %s\n", filepath.Join(directory, formFile), strings.Join(made, ", "))
	return nil
}

// formControl is the control one tagged field gets.
type formControl struct {
	field       string // the field's name
	label       string
	kind        string // "switch", "checkbox", "textfield", "slider", "choice", "select"
	placeholder string
	choices     string // the expression of the options: a package-level slice
	names       string // the function naming an option, or "nil"
}

type formStruct struct {
	name     string
	controls []formControl
}

// generateForms reads the package in directory and returns the source of formFile
// and the types it declares Form for: those in wanted, or every struct with a tagged
// field when wanted is empty.
func generateForms(directory string, wanted []string) ([]byte, []string, error) {
	files, err := os.ReadDir(directory)
	if err != nil {
		return nil, nil, err
	}
	fileSet := token.NewFileSet()
	packageName := ""
	var found []formStruct
	declared := map[string]bool{}
	for _, entry := range files {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || name == formFile {
			continue
		}
		file, err := parser.ParseFile(fileSet, filepath.Join(directory, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, nil, err
		}
		if packageName == "" {
			packageName = file.Name.Name
		} else if file.Name.Name != packageName {
			continue
		}
		structs, err := formStructs(fileSet, file, declared)
		if err != nil {
			return nil, nil, err
		}
		found = append(found, structs...)
	}
	if packageName == "" {
		return nil, nil, fmt.Errorf("form: no Go files in %s", directory)
	}
	var chosen []formStruct
	if len(wanted) == 0 {
		for _, s := range found {
			if len(s.controls) != 0 {
				chosen = append(chosen, s)
			}
		}
		if len(chosen) == 0 {
			return nil, nil, fmt.Errorf("form: no struct in %s has a field tagged form", directory)
		}
	} else {
		for _, name := range wanted {
			i := slicesIndex(found, name)
			switch {
			case !declared[name]:
				return nil, nil, fmt.Errorf("form: %s declares no struct type %s", directory, name)
			case i < 0 || len(found[i].controls) == 0:
				return nil, nil, fmt.Errorf("form: %s has no field tagged form", name)
			}
			chosen = append(chosen, found[i])
		}
	}
	sort.Slice(chosen, func(i, j int) bool { return chosen[i].name < chosen[j].name })
	var out bytes.Buffer
	fmt.Fprintf(&out, "%s\n\npackage %s\n\nimport \"github.com/vivaui/viva/ui\"\n", formHeader, packageName)
	made := make([]string, 0, len(chosen))
	for _, s := range chosen {
		writeForm(&out, s)
		made = append(made, s.name)
	}
	source, err := format.Source(out.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("form: generated code does not parse: %w", err)
	}
	return source, made, nil
}

func slicesIndex(structs []formStruct, name string) int {
	for i, s := range structs {
		if s.name == name {
			return i
		}
	}
	return -1
}

// formStructs returns the structs of file, with the controls of their tagged fields,
// and marks every struct type it declares in declared.
func formStructs(fileSet *token.FileSet, file *ast.File, declared map[string]bool) ([]formStruct, error) {
	uiName := ""
	for _, spec := range file.Imports {
		if path, _ := strconv.Unquote(spec.Path.Value); path == uiPath {
			uiName = "ui"
			if spec.Name != nil {
				uiName = spec.Name.Name
			}
		}
	}
	var structs []formStruct
	for _, decl := range file.Decls {
		general, ok := decl.(*ast.GenDecl)
		if !ok || general.Tok != token.TYPE {
			continue
		}
		for _, spec := range general.Specs {
			typeSpec := spec.(*ast.TypeSpec)
			body, ok := typeSpec.Type.(*ast.StructType)
			if !ok {
				continue
			}
			declared[typeSpec.Name.Name] = true
			s := formStruct{name: typeSpec.Name.Name}
			for _, field := range body.Fields.List {
				if field.Tag == nil {
					continue
				}
				raw, _ := strconv.Unquote(field.Tag.Value)
				tag := reflect.StructTag(raw)
				value, ok := tag.Lookup("form")
				if !ok || value == "-" {
					continue
				}
				where := fileSet.Position(field.Pos())
				fail := func(format string, arguments ...any) error {
					return fmt.Errorf("%s:%d: %s", where.Filename, where.Line, fmt.Sprintf(format, arguments...))
				}
				if typeSpec.TypeParams != nil {
					return nil, fail("form: %s is generic; give Form to a struct that is not", typeSpec.Name.Name)
				}
				if len(field.Names) == 0 {
					return nil, fail("form: an embedded field cannot be tagged form; tag the fields of its type and call its Form")
				}
				control, err := formControlOf(field.Type, uiName, value, tag)
				if err != nil {
					return nil, fail("form: field %s: %v", field.Names[0].Name, err)
				}
				for _, name := range field.Names {
					control.field = name.Name
					s.controls = append(s.controls, control)
				}
			}
			structs = append(structs, s)
		}
	}
	return structs, nil
}

// formControlOf chooses the control for a field of type expression typ, tagged
// form:"value" with the other keys of tag.
func formControlOf(typ ast.Expr, uiName, value string, tag reflect.StructTag) (formControl, error) {
	parts := strings.Split(value, ",")
	control := formControl{label: strings.TrimSpace(parts[0])}
	if control.label == "" {
		return control, errors.New(`form tag has no label: write form:"Label"`)
	}
	option := ""
	if len(parts) > 2 {
		return control, fmt.Errorf("form tag %q has more than one option", value)
	}
	if len(parts) == 2 {
		option = strings.TrimSpace(parts[1])
	}
	choices, hasChoices := tag.Lookup("choices")
	isFlex := func(name string) bool {
		selector, ok := typ.(*ast.SelectorExpr)
		if !ok || uiName == "" {
			return false
		}
		x, ok := selector.X.(*ast.Ident)
		return ok && x.Name == uiName && selector.Sel.Name == name
	}
	allow := func(options ...string) error {
		if option == "" {
			return nil
		}
		for _, o := range options {
			if o == option {
				return nil
			}
		}
		if len(options) == 0 {
			return fmt.Errorf("option %q does not apply to a %s", option, control.kind)
		}
		return fmt.Errorf("option %q does not apply to a %s (it takes %s)", option, control.kind, strings.Join(options, " or "))
	}
	_, hasPlaceholder := tag.Lookup("placeholder")
	switch {
	case hasChoices:
		control.kind = "choice"
		if err := allow("select"); err != nil {
			return control, err
		}
		if option == "select" {
			control.kind = "select"
		}
		list := strings.Split(choices, ",")
		if len(list) > 2 || strings.TrimSpace(list[0]) == "" {
			return control, fmt.Errorf(`choices tag %q: write choices:"options" or choices:"options,nameFunc", naming a package-level slice and a func(T) string`, choices)
		}
		control.choices, control.names = strings.TrimSpace(list[0]), "nil"
		if len(list) == 2 {
			control.names = strings.TrimSpace(list[1])
		}
		if len(list) == 1 && !isIdent(typ, "string") {
			return control, fmt.Errorf(`options that are not strings need a function naming them: choices:"%s,nameFunc"`, control.choices)
		}
		for _, expression := range []string{control.choices, control.names} {
			if _, err := parser.ParseExpr(expression); err != nil {
				return control, fmt.Errorf("choices tag %q: %q is not a Go expression", choices, expression)
			}
		}
	case isIdent(typ, "bool"):
		control.kind = "switch"
		if err := allow("checkbox"); err != nil {
			return control, err
		}
		if option == "checkbox" {
			control.kind = "checkbox"
		}
	case isFlex("Field"):
		control.kind = "textfield"
		if err := allow(); err != nil {
			return control, err
		}
		control.placeholder = tag.Get("placeholder")
	case isFlex("SliderState"):
		control.kind = "slider"
		if err := allow(); err != nil {
			return control, err
		}
	default:
		return control, fmt.Errorf("no control for its type: viva form makes a Switch for bool, a TextField for ui.Field, a Slider for ui.SliderState, and a Choice for a field with a choices tag")
	}
	if hasPlaceholder && control.kind != "textfield" {
		return control, fmt.Errorf("a placeholder tag applies to a ui.Field only")
	}
	return control, nil
}

func isIdent(expression ast.Expr, name string) bool {
	ident, ok := expression.(*ast.Ident)
	return ok && ident.Name == name
}

func writeForm(out *bytes.Buffer, s formStruct) {
	fmt.Fprintf(out, "\n// Form declares a control for each field of v tagged form, in a column.\nfunc (v *%s) Form(c ui.C) ui.Box {\n\treturn ui.Column(c).Gap(12).Children(func() {\n", s.name)
	for _, control := range s.controls {
		label := strconv.Quote(control.label)
		value := "&v." + control.field
		switch control.kind {
		case "switch":
			fmt.Fprintf(out, "\t\tui.Switch(c, %s, %s)\n", value, label)
		case "checkbox":
			fmt.Fprintf(out, "\t\tui.Checkbox(c, %s, %s)\n", value, label)
		case "textfield":
			fmt.Fprintf(out, "\t\tui.TextField(c, %s, %s, %s)\n", value, label, strconv.Quote(control.placeholder))
		default:
			call := ""
			switch control.kind {
			case "slider":
				call = fmt.Sprintf("ui.Slider(c, %s)", value)
			case "choice":
				call = fmt.Sprintf("ui.Choice(c, %s, %s, %s)", value, control.choices, control.names)
			case "select":
				call = fmt.Sprintf("ui.Select(c, %s, %s, %s)", value, control.choices, control.names)
			}
			fmt.Fprintf(out, "\t\tui.Column(c).Gap(6).Children(func() {\n\t\t\tui.Text(c, %s).Muted()\n\t\t\t%s\n\t\t})\n", label, call)
		}
	}
	out.WriteString("\t})\n}\n")
}
